# Compare the responses generated by two different prompts
from openai import OpenAI

client = OpenAI(
    api_key="YOUR_API_KEY",
    base_url="https://api.x.ai/v1"
)

question = "What is Artificial Intelligence?"

# Prompt 1 - Poor Prompt

poor_prompt = f"""
Tell me about AI.

Question:
{question}
"""

response1 = client.responses.create(
    model="grok-4-1-fast-reasoning",
    input=poor_prompt
)

poor_response = response1.output_text

# Prompt 2 - Well-Structured Prompt

good_prompt = f"""
You are an AI/ML tutor.

Explain Artificial Intelligence to a beginner.

Rules:
1. Use simple English.
2. Give a clear definition.
3. Provide three real-world examples.
4. Keep the answer concise.

Question:
{question}

Answer:
"""

response2 = client.responses.create(
    model="grok-4-1-fast-reasoning",
    input=good_prompt
)

good_response = response2.output_text

# Display Results

print("=" * 60)
print("PROMPT COMPARISON")
print("=" * 60)

print("\nUSER QUESTION:")
print(question)

print("\n" + "-" * 60)
print("PROMPT 1 - POOR PROMPT")
print("-" * 60)
print(poor_prompt)

print("\nRESPONSE 1:")
print(poor_response)

print("\n" + "-" * 60)
print("PROMPT 2 - WELL-STRUCTURED PROMPT")
print("-" * 60)
print(good_prompt)

print("\nRESPONSE 2:")
print(good_response)

print("\n" + "=" * 60)
print("COMPARISON")
print("=" * 60)

print("""
Response 1:
The poor prompt provides only a general instruction.
The response may be broad and less structured.

Response 2:
The well-structured prompt defines the AI's role,
target audience, language, required examples, and
response length.

Conclusion:
The well-structured prompt provides clearer instructions,
resulting in a more focused and useful response.
""")